"""BiSS C slave model: one sensor in a point-to-point connection, with its line.

The chip is the BiSS master: it drives MA (the clock) and reads SL (the data). This model
is the BiSS slave (Slave 0, SLI grounded) together with the transmission line, at logic
level: the RS-422 transceivers are not modelled, only the delay of the line. It drives
SL push-pull on every tick (the RS-422 receiver output at the master), idle high.

References: BiSS Association / iC-Haus "BiSS C Protocol Description" Rev D2 ("D2") and
"AN3: BiSS CRC Polynomials and Calculation" Rev E3 ("AN3"); the CRC is checked against
the examples of "AN21: CRC Verification for Microcontroller" Rev A1 ("AN21").

Timing model and delays
-----------------------
All times are chip ticks (`tick_ns`). The board hands every device the bus level of the
previous tick, so the model reacts one tick after MA changes: that tick is part of the
line delay. `line_delay_ns` is No. 7's tLineDelay as D2 measures it: from the second
rising edge at MA (ACK) at the master to the first falling edge of SL at the master. The
model makes the total exactly `ld = max(1, round(line_delay_ns / tick_ns))` ticks: the
one-tick board reaction plus `ld - 1` ticks of delay split between the way out (MA at the
master -> MAI at the slave, a share `ma_delay_share`, default half, rounded down) and the
way back (SLO -> SL). Everything the slave does (edge counting, timeouts, the CDM sample)
works on the delayed MAI; everything it sends is delayed again on the way back.

How SL is generated (D2 POINT-TO-POINT CONNECTION, Figures 4, 6, 7, 8, 17)
------------------------------------------------------------------------
The slave generates every bit on a rising edge of MAI (D2 Figure 4: "generate their data
signals on the rising edge"; the slave's sample point, the falling edge, only matters for
the CDM bit, which is read at the end of the timeout). With LAT the first rising edge
(index 0) of a frame, which starts with a falling edge from idle (D2 BiSS FRAME, Header):
  * idle: SL = 1 (D2 Idle);
  * LAT (edge 0): data and CDS are latched (D2 Latch Point, Figure 16); SL stays 1;
  * edge 1: ACK = 0 (D2 Header, Figure 7);
  * edges 2..: 0 until the processing time has passed: the start bit is sent on the
    first rising edge k >= 2 at which at least `busy_ns` (D2 Processing Time, No. 10a)
    have passed since LAT, after another `busy_clocks` zeros (No. 10b, busy_s); with
    busy_ns = busy_clocks = 0 the start bit is edge 2 (tbusy = 2 TMA, the minimum);
  * STR = 1, then CDS, then the data channel MSB first (`dlen` bits, D2 Data Channels,
    Figure 8), then the CRC MSB first, inverted (D2 Data Channels; AN3 Figure 1);
  * STP: the next rising edge after the CRC LSB sends the stop bit 0 (D2 Timeout:
    "the stop bit is generated by the BiSS Slave at the last rising edge on MAI (STP)").
    Any further rising edge keeps SL at 0 (D2 Daisy Chain: when the master stops
    toggling MA, SLO is set low);
  * timeout: the slave's timer restarts on every MAI edge; when MAI has not changed for
    the timeout, SL goes to 1, CDM is read from MAI and the slave is idle again (D2
    Timeout, Figures 9-11). A frame cut short ends the same way: SL keeps the bit it was
    sending until the timeout expires, then goes to 1.
The timeout is "static": `tto_us` (No. 5, 12.5-40 us), or "adaptive": tTOA_ref, the time
from the first falling to the second rising edge at MAI (1.5 TMA at a 50 % duty cycle;
No. 6 note 3, Figure 12), measured afresh in every frame and used from the ACK edge on;
before the ACK edge the static timeout is the limit (D2 Adaptive Timeout). The model's
sample clock is the chip tick, so tTOA = tTOA_ref + 0 TCLK (within No. 6).

CDM mapping (D2 Timeout, Figure 9; CONTROL COMMUNICATION: "CDM bits (inverted before
transmission)"): the slave samples MAI when the timeout expires; MAI high means CDM = 0,
MAI low means CDM = 1. So `cdm = 1 - (MAI level at the end of the timeout)`.

Process data and CRC (D2 PROCESS DATA COMMUNICATION; AN3)
--------------------------------------------------------
`data` is an int (sent every frame) or a list, one value per frame, taken at LAT (D2
Latch Point); when the list runs out the last value is repeated. An INIT frame (below)
does not use up a value. `cds` works the same way (an int 0/1 or a list). The CRC covers
the data bits only (AN3 "All data bits of the data channel DMSB ... DLSB"); `crc_bits`
selects the AN3 Table 1 polynomial: 4 -> 0x13, 5 -> 0x25, 6 -> 0x43 (default; start value
0, inverted before transmission), 16 -> 0x190D9; 0 sends no CRC. `crc6(value, nbits)`
returns the AN3 CRC before inversion (AN3 code example, start value 0); what goes on the
line is its complement. Null Value (D2 Null Value): the fault "null" sends all-zero data.

Faults: `faults` maps a fault name to a frame index or a collection of frame indices
(indices into `frames`, 0-based, every frame counted):
  * "crc": the CRC sent is wrong (its LSB flipped after inversion);
  * "silent": the slave does not answer: SL stays 1 for the whole frame (no ACK);
  * "no_start": ACK is sent, the start bit never comes (SL stays 0 until the timeout);
  * "null": the Null Value (all data bits 0, with its correct CRC) is sent instead.
The frame-structure checks (cut short, extra clocks) are skipped in "silent" and
"no_start" frames, because the master can only give up on them. All but "null" count as
an error for the 40 us break rule below.

Records
-------
`frames`: one dict per frame, appended at LAT and completed when the timeout expires:
  "t": tick at which the slave saw LAT; "t_ma": tick of that LAT edge at the master pin;
  "data": the value sent (None if the frame never reached its start bit);
  "latched": the value latched at LAT; "cds": the CDS bit sent;
  "crc": the CRC bits as sent (inverted, after any fault), an int, MSB = first sent;
  "cdm": the CDM bit read at the end of the timeout (None while the timeout runs);
  "complete": True when the master clocked the frame up to STP (False when cut short,
  and in "silent"/"no_start" frames); "clocks": rising MAI edges in the frame, LAT and
  any edges after STP included; "tma_ns": mean clock period (rising to rising) of the
  frame's clocks; "tbusy_ns": time from LAT to the start bit edge (No. 10a);
  "init": True for an accepted INIT frame; "fault": the fault applied, or None.
`violations`: messages "t=<tick>: <what> (<reference>)", tick = the slave's tick of the
event. `errors()` returns them all; `finish()` closes an open frame and returns them.

Checks (each failure appends a violation; each kind at most once per frame)
-----------------------------------------------------------------------------
  1. D2 Table 10 No. 1: every clock period of a frame (rising to rising MAI edge) is
     within 80 kHz .. 10 MHz (12.5 us .. 100 ns).
  2. D2 Table 10 Nos. 3/4: every MAI low phase (falling to rising, LAT's included) and
     every high phase of a frame is at least 40 % of TMA_min, the slave's minimum clock
     period, `tma_min_ns` (No. 1 note 1: stored in the EDS; default 100 ns = 10 MHz).
  3. Frame cut short (D2 BiSS FRAME, Timeout, Figures 6, 9): the master must clock the
     whole frame up to STP. If the slave's timeout expires before STP, the frame is
     recorded with complete=False and a violation is logged. Exception, the INIT frame of
     D2 Bus Reset/Initialization (Figure 22, APPLICATION HINTS step 6): the first frame
     after power-up may stop after LAT and ACK ("at least two low pulses") before the
     start bit; it is recorded with init=True. `reduced_ok=True` accepts such a frame
     (stopped after >= 2 clocks, before the start bit) at any time (D2 Reduced BiSS
     Frame, Figure 36), still recorded incomplete.
  4. Stop clocking after STP (D2 Timeout: the master stops the clock, the stop bit is
     generated at the last rising edge): a rising edge after STP is an extra clock. A
     master whose frame is shifted by the line delay (D2 Line Delay, Figure 13: extra ACK
     clocks) legitimately makes up to e_max more: e_max = ceil((ld + lag - h + 1) / TMA),
     the number of clocks a master sampling at the falling edge (Figure 4) or any later
     point needs, with ld the total line delay, lag = `master_lag_ns` (the master's own
     input synchroniser), h the shortest high phase of the frame, TMA its mean period.
     A rising edge beyond those, before the timeout expired, is a violation: "extra clock
     after STP" when the falling edge before it came at clock pace (within one TMA of
     the previous rising edge), else "new frame during the timeout" (below). A first
     falling edge after STP, with MA then held low, is the CDM = 1 level (Figure 9) and
     is fine; so is the release of a held CDM after the timeout (Figure 27).
  5. Timeout handshake (D2 Timeout: the handshake "ensures that the BiSS Master does not
     start another BiSS cycle before all connected BiSS Slaves are ready"; BiSS Cycle
     note: the frame "must be finished by the Timeout indicated with the rising edge on
     SLO before the next BiSS cycle is started"): a new frame's falling MA edge must not
     come before SL is back high at the master. If the slave sees it before its timeout
     expired, it is absorbed as more clocks of the old frame (as a real slave's timer
     would) and flagged by check 4; if it comes after the slave expired but before the
     rising SL reached the master pin (line delay), it is flagged at that frame's LAT.
  6. Bus Reset/Initialization (D2 PROCESS DATA COMMUNICATION, Bus Reset; APPLICATION
     HINTS step 5): "after power-on and after an error, the BiSS Master must break BiSS
     communication for 40 us before starting a new frame". Power-on is tick 0: MA must be
     high for 40 us (since tick 0, or since MA last rose before the first frame) before
     the first frame's falling edge. After an error frame (faults crc/silent/no_start, or
     a frame cut short) the next frame's falling edge must come at least 40 us after the
     error frame's last rising MA edge. A frame start is confirmed by its LAT edge: a
     low pulse on MA that times out without a rising edge is no frame.
  7. Minimum cycle time (D2 Table 10 No. 12; APPLICATION HINTS, Calculation of BiSS
     Cycle Time). Reading: No. 12 says every slave supports a cycle time of 250 us; it
     limits slaves, not masters. The master's rule is not to underrun the calculated
     minimum (frame + timeout, which checks 3-5 already enforce through the handshake)
     nor the slave's absolute minimum, if it has one. `cycle_min_us` (default None: no
     check) is that absolute minimum (<= 250 us by No. 12); frame starts closer than it
     (falling edge to falling edge) are a violation.
  Configuration limits are checked at construction (ValueError): No. 5 (tto 12.5-40 us),
  No. 7 (line delay <= 40 us), No. 10a (busy_ns <= 40 us), No. 10b (busy_clocks 0-8),
  No. 12 (cycle_min_us <= 250), dlen 1-64 (D2 Data Channels: up to 64 bits), CRC length.
`finish()` also flags a frame still open before its STP when the run ends.
"""

from __future__ import annotations

import math
from collections import deque

from .board import Board, Device

CRC_POLYS = {4: 0x13, 5: 0x25, 6: 0x43, 16: 0x190D9}   # AN3 Table 1
FAULTS = ("crc", "silent", "no_start", "null")
ERROR_FAULTS = ("crc", "silent", "no_start")
_REF_TO = "D2 BiSS FRAME, Timeout, Figure 9"


def crc_biss(value: int, nbits: int, poly: int = 0x43) -> int:
    """AN3 CRC of the `nbits` low bits of `value`, MSB first, start value 0, NOT inverted.

    `poly` includes the leading 1 (0x43 = x^6 + x^1 + x^0). Same shift register as the
    AN3 code example (cExOr = data bit XOR CRC MSB, shifted in with the polynomial taps).
    """
    order = poly.bit_length() - 1
    mask = (1 << order) - 1
    p = poly & mask
    top = order - 1
    crc = 0
    for i in range(nbits - 1, -1, -1):
        fb = ((value >> i) & 1) ^ (crc >> top)
        crc = (crc << 1) & mask
        if fb:
            crc ^= p
    return crc


def crc6(value: int, nbits: int) -> int:
    """AN3 6-bit process data CRC (polynomial 0x43, start 0), before the inversion."""
    return crc_biss(value, nbits, 0x43)


class BissSlave(Device):
    def __init__(self, ma=0, sl=1, tick_ns=40.0, dlen=26, data=0, crc_bits=6,
                 line_delay_ns=0.0, busy_ns=0.0, busy_clocks=0, timeout="static",
                 tto_us=20.0, cds=0, faults=None, tma_min_ns=100.0, master_lag_ns=80.0,
                 ma_delay_share=0.5, cycle_min_us=None, reduced_ok=False):
        if not 1 <= dlen <= 64:
            raise ValueError("dlen must be 1..64 (D2 Data Channels)")
        if crc_bits and crc_bits not in CRC_POLYS:
            raise ValueError(f"crc_bits must be 0 or one of {sorted(CRC_POLYS)} (AN3 Table 1)")
        if timeout not in ("static", "adaptive"):
            raise ValueError('timeout must be "static" or "adaptive"')
        if not 12.5 <= tto_us <= 40.0:
            raise ValueError("tto_us must be 12.5..40 us (D2 Table 10 No. 5)")
        if not 0 <= line_delay_ns <= 40000:
            raise ValueError("line_delay_ns must be 0..40 us (D2 Table 10 No. 7)")
        if not 0 <= busy_ns <= 40000:
            raise ValueError("busy_ns must be <= 40 us (D2 Table 10 No. 10a)")
        if not 0 <= busy_clocks <= 8:
            raise ValueError("busy_clocks must be 0..8 (D2 Table 10 No. 10b)")
        if cycle_min_us is not None and not 0 < cycle_min_us <= 250:
            raise ValueError("cycle_min_us must be <= 250 us (D2 Table 10 No. 12)")
        self.ma, self.sl = ma, sl
        self._mask = 1 << sl
        self.tick_ns = tick_ns
        self.dlen, self.crc_bits = dlen, crc_bits
        self._poly = CRC_POLYS.get(crc_bits, 0)
        self._dmask = (1 << dlen) - 1
        self._cmask = (1 << crc_bits) - 1
        self._data, self._data_last = self._source(data, self._dmask, "data")
        self._cds, self._cds_last = self._source(cds, 1, "cds")
        self.faults: dict[str, set[int]] = {}
        for name, idx in (faults or {}).items():
            if name not in FAULTS:
                raise ValueError(f"unknown fault {name!r}; known: {FAULTS}")
            if name == "crc" and not crc_bits:
                raise ValueError("fault 'crc' needs crc_bits > 0")
            self.faults[name] = {idx} if isinstance(idx, int) else set(idx)
        tk = lambda ns: ns / tick_ns
        # line delay: ld ticks in total, 1 of them the board's own reaction
        self._ld = max(1, round(tk(line_delay_ns)))
        extra = self._ld - 1
        self._din = int(extra * ma_delay_share)
        self._dout = extra - self._din
        self._qin = deque([1] * self._din)
        self._qout = deque([1] * self._dout)
        self._lag = tk(master_lag_ns)
        self._adaptive = timeout == "adaptive"
        self._tto_static = max(1, round(tk(tto_us * 1000.0)))
        self._busy = tk(busy_ns)
        self._busy_clocks = busy_clocks
        self._ph_min = 0.4 * tk(tma_min_ns)            # Nos. 3/4, in ticks
        self._per_min, self._per_max = tk(100.0), tk(12500.0)   # No. 1
        self._t40 = tk(40000.0)                         # Bus Reset: 40 us
        self._cyc = None if cycle_min_us is None else tk(cycle_min_us * 1000.0)
        self.reduced_ok = reduced_ok
        self.frames: list[dict] = []
        self.violations: list[str] = []
        # state
        self._state = 0          # 0 idle, 1 in a frame (from the falling edge to timeout)
        self._pm = 1             # last MAI level seen
        self._sl = 1             # SLO before the return delay
        self._mute = 0           # 1: SL forced high (fault "silent")
        self._t_hi = 1 + self._din    # MAI high since (power-on = master tick 0)
        self._t_edge = self._t_fall = self._t_fall0 = self._t_rise = 0
        self._tto = self._tto_static
        self._k = -1
        self._fr = None
        self._seen: set[str] = set()
        self._t_exp = None       # tick of the last timeout expiry
        self._t_last_clk = 0     # last rising edge of the previous frame
        self._err = False        # previous frame was an error frame
        self._prev_fall0 = None
        self._popped = False

    # ---------------------------------------------------------------- sources
    @staticmethod
    def _source(x, mask, name):
        if isinstance(x, int):
            vals = [x]
            q = None
        else:
            vals = list(x)
            q = deque(vals)
            if not vals:
                raise ValueError(f"{name} list is empty")
        for v in vals:
            if not 0 <= v <= mask:
                raise ValueError(f"{name} value {v} does not fit (max {mask})")
        return q, vals[0]

    def _take(self, which):
        q = self._data if which == "data" else self._cds
        if q is None:
            return (self._data_last if which == "data" else self._cds_last), False
        if q:
            v = q.popleft()
            if which == "data":
                self._data_last = v
            else:
                self._cds_last = v
            return v, True
        return (self._data_last if which == "data" else self._cds_last), False

    # ---------------------------------------------------------------- helpers
    def _viol(self, key, t, msg):
        if key in self._seen:
            return
        self._seen.add(key)
        self.violations.append(f"t={t}: {msg}")

    def _fault_of(self, idx):
        for name in FAULTS:
            s = self.faults.get(name)
            if s and idx in s:
                return name
        return None

    # ---------------------------------------------------------------- the tick
    def step(self, t, bus):
        m = (bus >> self.ma) & 1
        if self._din:
            q = self._qin
            q.append(m)
            m = q.popleft()
        if m != self._pm:
            self._pm = m
            if m:
                self._rise(t)
            else:
                self._fall(t)
        elif self._state and t - self._t_edge >= self._tto:
            self._expire(t, m)
        sl = self._sl | self._mute
        if self._dout:
            q = self._qout
            q.append(sl)
            sl = q.popleft()
        return (0, self._mask) if sl else (self._mask, 0)

    def _fall(self, t):
        if not self._state:                  # frame start (confirmed at LAT)
            self._state = 1
            self._k = -1
            self._fr = None
            self._seen = set()
            self._tto = self._tto_static
            self._t_fall0 = self._t_fall = self._t_edge = t
            self._f_hi = self._t_hi
            return
        self._t_edge = t
        k = self._k
        if k >= 0:
            hi = t - self._t_rise
            stp = self._stp
            if stp is None or k - stp <= self._emax:
                if hi < self._ph_min:
                    self._viol("no4", t, f"MA high {hi * self.tick_ns:.0f} ns, under 40 % of "
                               f"TMA_min (D2 Table 10 No. 4)")
                if stp is None and hi < self._hmin:
                    self._hmin = hi
        self._rise_before_fall = self._t_rise
        self._t_fall = t

    def _rise(self, t):
        if not self._state:
            self._t_hi = t                   # idle rise: power-up level or CDM release
            return
        self._t_edge = t
        low = t - self._t_fall
        k = self._k + 1
        self._k = k
        stp = self._stp if k else None
        legit = stp is None or k - stp <= self._emax
        if legit and low < self._ph_min:
            self._viol("no3", t, f"MA low {low * self.tick_ns:.0f} ns, under 40 % of TMA_min "
                       f"(D2 Table 10 No. 3)")
        if k == 0:
            self._lat(t)
            return
        if legit:
            per = t - self._t_rise
            if not self._per_min <= per <= self._per_max:
                self._viol("no1", t, f"MA clock period {per * self.tick_ns:.0f} ns "
                           f"({1e6 / (per * self.tick_ns):.1f} kHz) outside 80 kHz..10 MHz "
                           f"(D2 Table 10 No. 1)")
            self._t_last_legit, self._n_legit = t, k
        self._t_rise = t
        fr = self._fr
        if k == 1:                           # ACK
            if self._adaptive:
                self._tto = t - self._t_fall0    # tTOA_ref (No. 6 note 3, Figure 12)
            self._sl = 0
            return
        if stp is not None:                  # after STP
            self._sl = 0
            post = k - stp
            if post > self._emax and fr["fault"] != "silent":
                tf, tr = self._t_fall, self._rise_before_fall
                if tf - tr <= self._tavg:
                    self._viol("extra", t, f"MA rising edge {post} after STP before the "
                               f"timeout expired (line delay allows {self._emax}): extra "
                               f"clock, the master must stop clocking at STP ({_REF_TO})")
                else:
                    self._viol("newframe", tf, f"falling MA (new frame) before the slave's "
                               f"timeout expired and SL was back high: timeout handshake "
                               f"({_REF_TO}; D2 BiSS Cycle)")
            return
        if self._bi is None:                 # header: waiting for the start bit
            if fr["fault"] == "no_start":
                self._sl = 0
                return
            if self._busy_rem is None:
                if t - self._t_lat < self._busy:
                    self._sl = 0
                    return
                self._busy_rem = self._busy_clocks
            if self._busy_rem:
                self._busy_rem -= 1
                self._sl = 0
                return
            self._bi = 0
            fr["data"] = None if self._mute else fr["latched"]
            fr["tbusy_ns"] = (t - self._t_lat) * self.tick_ns
            self._sl = 1                     # STR
            return
        bi = self._bi + 1
        self._bi = bi
        bits = self._bits
        if bi < len(bits):
            self._sl = bits[bi]
            return
        # STP: stop bit
        self._sl = 0
        self._stp = k
        fr["complete"] = not self._mute
        self._tavg = (t - self._t_lat) / k
        h = self._hmin if self._hmin != math.inf else self._tavg / 2
        self._emax = max(0, math.ceil((self._ld + self._lag - h + 1) / self._tavg))

    def _lat(self, t):
        idx = len(self.frames)
        tf = self._t_fall0
        us = lambda ticks: ticks * self.tick_ns / 1000.0
        if idx == 0:
            if tf - self._f_hi < self._t40:
                self._viol("reset", tf, f"first frame {us(tf - self._f_hi):.1f} us after "
                           f"power-on/MA high, under 40 us (D2 Bus Reset/Initialization)")
        else:
            if self._t_exp is not None and tf - 1 - self._din < self._t_exp + self._dout:
                self._viol("handshake", tf, f"new frame started before SL was back high at "
                           f"the master: timeout handshake ({_REF_TO}; D2 BiSS Cycle)")
            if self._err and tf - self._t_last_clk < self._t40:
                self._viol("errbreak", tf, f"new frame {us(tf - self._t_last_clk):.1f} us "
                           f"after an error frame's last clock, under 40 us "
                           f"(D2 Bus Reset/Initialization)")
            if self._cyc is not None and tf - self._prev_fall0 < self._cyc:
                self._viol("cycle", tf, f"cycle time {us(tf - self._prev_fall0):.1f} us under "
                           f"the slave's minimum (D2 Table 10 No. 12)")
        self._prev_fall0 = tf
        fault = self._fault_of(idx)
        value, popped = self._take("data")
        cds, _ = self._take("cds")
        self._popped = popped
        if fault == "null":
            value = 0
        crc = 0
        if self.crc_bits:
            crc = ~crc_biss(value, self.dlen, self._poly) & self._cmask
            if fault == "crc":
                crc ^= 1
        bits = [1, cds]
        bits += [(value >> i) & 1 for i in range(self.dlen - 1, -1, -1)]
        bits += [(crc >> i) & 1 for i in range(self.crc_bits - 1, -1, -1)]
        self._bits = bits
        self._fr = {"t": t, "t_ma": t - 1 - self._din, "data": None, "latched": value,
                    "crc": crc, "cds": cds, "cdm": None, "complete": False, "clocks": 1,
                    "tma_ns": None, "tbusy_ns": None, "init": False, "fault": fault}
        self.frames.append(self._fr)
        self._mute = 1 if fault == "silent" else 0
        self._t_lat = self._t_rise = self._t_last_legit = t
        self._n_legit = 0
        self._bi = self._busy_rem = self._stp = None
        self._hmin = math.inf
        self._emax = 0
        self._tavg = 0

    def _expire(self, t, m):
        fr = self._fr
        self._state = 0
        self._sl = 1
        self._mute = 0
        self._t_exp = t
        if fr is None:                       # a low pulse without LAT: no frame
            return
        self._fr = None
        fr["cdm"] = 1 - m
        fr["clocks"] = self._k + 1
        if self._n_legit:
            fr["tma_ns"] = (self._t_last_legit - fr["t"]) / self._n_legit * self.tick_ns
        self._t_last_clk = self._t_rise
        fault = fr["fault"]
        err = fault in ERROR_FAULTS
        if not fr["complete"] and fault not in ("silent", "no_start"):
            short = self._bi is None and self._k >= 1
            if short and len(self.frames) == 1:
                fr["init"] = True            # INIT frame (Figure 22): keep the data value
                if self._popped and self._data is not None:
                    self._data.appendleft(fr["latched"])
            elif short and self.reduced_ok:
                pass
            else:
                self._viol("cut", t, f"frame cut short: timeout after {self._k + 1} clocks, "
                           f"before STP; the master must clock the complete frame "
                           f"(D2 BiSS FRAME, Figures 6, 9)")
                err = True
        self._err = err

    # ---------------------------------------------------------------- results
    def errors(self):
        return list(self.violations)

    def finish(self):
        fr = self._fr
        if self._state and fr is not None and not fr["complete"] \
                and fr["fault"] not in ("silent", "no_start"):
            self._viol("open", self._t_edge, "run ended inside a frame before STP "
                       "(D2 BiSS FRAME, Figure 6)")
        return self.errors()


# ==================================================================== self-test
class _Master:
    """Synthetic bit-banged BiSS master on the chip side of a Board (self-test only).

    Clocks MA, searches the ACK by oversampling SL every tick (the delay inside the
    acknowledge period sets the sample point for the remaining bits, D2 Line Delay,
    Figure 13: extra ACK clocks shift the frame), samples each bit half a period after
    it appears, finds the start bit, CDS, data, CRC, stop bit and the timeout end.
    """

    def __init__(self, slave, tick_ns=40.0, ma=0, sl=1, start_us=45.0):
        self.board = Board(slave, record=False)
        self.ma, self.sl = ma, sl
        self.us = 1000.0 / tick_ns
        self.t = 0
        self.H: list[int] = []
        self.last_rise = 0
        self.tick(1, int(start_us * self.us))

    def tick(self, lvl, n=1):
        b, ma, sl, H = self.board, self.ma, self.sl, self.H
        for _ in range(n):
            v = b(self.t, lvl << ma, 1 << ma)
            H.append((v >> sl) & 1)
            self.t += 1

    def wait_until(self, lvl, cond, limit):
        end = self.t + limit
        while self.t < end and not cond():
            self.tick(lvl)

    def frame(self, hi, lo, dlen, crcb, poly=0x43, cdm=0, cut_after=None, extra=0,
              wait_end=True):
        T = hi + lo
        H = self.H
        rises: list[int] = []
        self.tick(0, lo)
        ack = scan = str_p = stop_edge = err = p_next = None
        lim = 40 * self.us + 2 * T
        while True:
            rises.append(self.t)
            self.tick(1, hi)
            n = len(rises) - 1
            if ack is None and n >= 1:
                scan = rises[1] if scan is None else scan
                while scan < self.t:
                    if H[scan] == 0:
                        j = max(i for i, r in enumerate(rises) if r <= scan)
                        ack, p_next = (j, scan - rises[j]), j + 1
                        break
                    scan += 1
            if ack is not None and str_p is None:
                while p_next < len(rises):
                    s = rises[p_next] + ack[1] + T // 2
                    if s >= self.t:
                        break
                    if H[s]:
                        str_p, stop_edge = p_next, p_next + 2 + dlen + crcb
                        break
                    p_next += 1
            if cut_after is not None and len(rises) >= cut_after:
                err = "cut"
                break
            if stop_edge is not None and n >= stop_edge + extra:
                break
            if ack is None and n >= 1 and self.t - rises[1] > lim:
                err = "no_ack"
                break
            if ack is not None and str_p is None and self.t - rises[0] > lim + 9 * T * (ack[0] + 1):
                err = "no_start"
                break
            self.tick(0, lo)
        self.last_rise = rises[-1]
        res = {"err": err, "clocks": len(rises), "rises": rises,
               "ack_extra": None if ack is None else ack[0] - 1}
        if err:
            # error: break 41 us after the last clock, and SL must be high
            self.wait_until(1, lambda: self.t - self.last_rise > 41 * self.us and H[-1] == 1,
                            int(200 * self.us))
            return res
        lvl = 0 if cdm else 1
        if lvl == 0:
            self.tick(0)
        sample = lambda p: rises[p] + ack[1] + T // 2
        s_stop = sample(stop_edge)
        self.wait_until(lvl, lambda: self.t > s_stop + 1, int(100 * self.us))
        bits = [H[sample(p)] for p in range(str_p + 1, stop_edge + 1)]
        cds, dbits, cbits, stop = bits[0], bits[1:1 + dlen], bits[1 + dlen:-1], bits[-1]
        data = int("".join(map(str, dbits)), 2)
        crc = int("".join(map(str, cbits)), 2) if crcb else 0
        exp = (~crc_biss(data, dlen, poly) & ((1 << crcb) - 1)) if crcb else 0
        res.update(cds=cds, data=data, crc=crc, crc_ok=crc == exp, stop=stop, end=None)
        if not wait_end:
            return res
        self.wait_until(lvl, lambda: H[-1] == 1, int(100 * self.us))
        res["end"] = self.t - 1 if H[-1] == 1 else None
        if lvl == 0:
            self.tick(1)                     # release the held CDM (Figure 27)
        return res


def _selftest(verbose: bool = False) -> bool:
    ok = True

    def check(cond, what):
        nonlocal ok
        if not cond:
            ok = False
            print("FAIL:", what)
        elif verbose:
            print("ok:", what)

    # CRC against AN21 (6-bit example: data 010011010101 -> 0x1C as sent, i.e. inverted;
    # 16-bit example: 0xD9CFE0C0DA -> 0x5F29 inverted) and a hand-checked value.
    check((~crc6(0b010011010101, 12)) & 0x3F == 0x1C, "AN21 6-bit CRC example")
    check((~crc_biss(0xD9CFE0C0DA, 40, 0x190D9)) & 0xFFFF == 0x5F29, "AN21 16-bit CRC example")
    check(crc6(1, 1) == 0x03 and crc6(0, 26) == 0, "hand-checked CRC (1 -> x^1+1, 0 -> 0)")

    def run(name, slave_kw, frames, hi=12, lo=13, gap=5, start_us=45.0, crcb=6, poly=0x43,
            expect=()):
        nonlocal ok
        s = BissSlave(**slave_kw)
        m = _Master(s, tick_ns=s.tick_ns, start_us=start_us)
        dlen = s.dlen
        results = []
        for f in frames:
            kw = dict(f)
            fh, fl = kw.pop("hi", hi), kw.pop("lo", lo)
            g = kw.pop("gap", gap)
            r = m.frame(fh, fl, dlen, crcb, poly=poly, **kw)
            results.append(r)
            m.tick(1, g)
        m.tick(1, int(60 * m.us))
        errs = s.finish()
        if verbose and expect:
            print(f"   {name}: {errs}")
        if expect:
            for key in expect:
                check(any(key in e for e in errs), f"{name}: violation '{key}' reported")
        else:
            check(not errs, f"{name}: no violations {errs[:3]}")
        return s, results

    def legal(name, kw, values, cdms, hi=12, lo=13, crcb=6, poly=0x43, faults=None,
              init=False):
        kw = dict(kw, data=values)
        if faults:
            kw["faults"] = faults
        frames = []
        if init:
            frames.append(dict(cut_after=2))
        errs = {x for f, x in (faults or {}).items() if f in ERROR_FAULTS}
        for i in range(len(values)):
            j = i + (1 if init else 0)
            # after an error frame the master breaks for 40 us (D2 Bus Reset)
            frames.append(dict(cdm=cdms[i % len(cdms)], gap=1200 if j in errs else 5))
        s, res = run(name, kw, frames, hi=hi, lo=lo, crcb=crcb, poly=poly)
        if init:
            check(s.frames[0]["init"] and not s.frames[0]["complete"], f"{name}: INIT frame")
            res, frs = res[1:], s.frames[1:]
        else:
            frs = s.frames
        check(len(frs) == len(values), f"{name}: {len(frs)} frames recorded")
        flt = faults or {}
        for i, (r, fr) in enumerate(zip(res, frs)):
            j = i + (1 if init else 0)
            fault = next((f for f, x in flt.items() if x == j), None)
            want = 0 if fault == "null" else values[i]
            if fault == "silent":
                check(r["err"] == "no_ack" and fr["data"] is None and not fr["complete"],
                      f"{name} frame {j}: silent -> master sees no ACK")
                continue
            if fault == "no_start":
                check(r["err"] == "no_start" and fr["data"] is None and not fr["complete"],
                      f"{name} frame {j}: no start bit")
                continue
            check(r["err"] is None, f"{name} frame {j}: master error {r['err']}")
            if r["err"]:
                continue
            check(r["data"] == want == fr["data"], f"{name} frame {j}: data "
                  f"{r['data']:#x} sent {fr['data']} want {want:#x}")
            check(r["crc"] == fr["crc"], f"{name} frame {j}: crc as sent")
            check(r["crc_ok"] == (fault != "crc"), f"{name} frame {j}: crc check {r['crc_ok']}")
            check(r["cds"] == kw.get("cds", 0) == fr["cds"], f"{name} frame {j}: cds")
            check(r["stop"] == 0, f"{name} frame {j}: stop bit 0")
            check(r["end"] is not None, f"{name} frame {j}: timeout end (SL high)")
            check(fr["cdm"] == cdms[i % len(cdms)], f"{name} frame {j}: cdm {fr['cdm']}")
            check(fr["complete"], f"{name} frame {j}: complete")
            check(abs(fr["tma_ns"] - (hi + lo) * s.tick_ns) < 1, f"{name} frame {j}: tma")
            exp_extra = (s._ld) // (hi + lo)
            check(r["ack_extra"] == exp_extra, f"{name} frame {j}: extra ACK clocks "
                  f"{r['ack_extra']} (expected {exp_extra})")
        return s, res

    vals26 = [0x2ABCDEF, 0x0000001, 0x3FFFFFF, 0x1234567]
    legal("static, no line delay, 1 MHz", dict(dlen=26, cds=1), vals26, [0, 1])
    s, _ = legal("line delay 0.7 TMA, adaptive, busy 5 us",
                 dict(dlen=13, line_delay_ns=700, timeout="adaptive", busy_ns=5000),
                 [0x1ABC, 0x0001, 0x1FFF], [1, 0])
    check(s.frames[0]["tbusy_ns"] == 5000, f"busy 5 us: tbusy {s.frames[0]['tbusy_ns']}")
    s, _ = legal("line delay 2.3 TMA, busy_clocks 3, static 15 us",
                 dict(dlen=32, line_delay_ns=2300, busy_clocks=3, tto_us=15),
                 [0xDEADBEEF, 0x01234567], [0, 1, 1])
    check(s.frames[0]["tbusy_ns"] == 5 * 1000, f"busy_clocks 3: tbusy {s.frames[0]['tbusy_ns']}")
    legal("6.25 MHz clock, adaptive", dict(dlen=26, timeout="adaptive"), vals26, [0, 1],
          hi=2, lo=2)
    legal("100 kHz clock, static 20 us, line delay 1.5 us", dict(dlen=12, line_delay_ns=1500),
          [0x4D5, 0xABC], [1, 0], hi=125, lo=125)
    legal("16-bit CRC, 40-bit data", dict(dlen=40, crc_bits=16), [0xD9CFE0C0DA, 0x1], [0],
          crcb=16, poly=0x190D9)
    legal("INIT frame first, then data", dict(dlen=26), [0x155, 0x2AA], [0], init=True)
    legal("faults crc/silent/no_start/null",
          dict(dlen=26, faults=None), [0x111, 0x222, 0x333, 0x444, 0x555], [0],
          faults={"crc": 1, "silent": 2, "no_start": 3, "null": 4})

    # illegal masters
    run("clock too fast (12.5 MHz)", dict(dlen=8), [dict(hi=1, lo=1)], expect=("No. 1",))
    s, _ = run("frame cut short", dict(dlen=26), [dict(cut_after=12), dict()],
               expect=("cut short",))
    check(not s.frames[0]["complete"] and s.frames[1]["complete"], "cut frame recorded incomplete")
    run("new frame during the timeout", dict(dlen=8),
        [dict(wait_end=False, gap=int(3 * 25)), dict()], expect=("new frame",))
    run("new frame after expiry but before SL high at the master",
        dict(dlen=8, line_delay_ns=4000, tto_us=12.5),
        [dict(wait_end=False, gap=int(12.5 * 25) + 15), dict(gap=2000)], expect=("handshake",))
    run("extra clocks after STP", dict(dlen=8), [dict(extra=2), dict()],
        expect=("extra clock",))
    run("extra clocks after STP with line delay", dict(dlen=8, line_delay_ns=2300),
        [dict(extra=2), dict()], expect=("extra clock",))
    run("first frame too soon after power-on", dict(dlen=8), [dict()], start_us=10,
        expect=("Bus Reset",))
    run("no 40 us break after a CRC error", dict(dlen=8, faults={"crc": 0}),
        [dict(), dict(gap=1)], expect=("error frame",))
    run("cycle time under the slave minimum", dict(dlen=8, cycle_min_us=100, timeout="adaptive"),
        [dict(), dict()], expect=("No. 12",))
    run("MA low phase under 40 % TMA_min", dict(dlen=8, tma_min_ns=1000), [dict(hi=20, lo=5)],
        expect=("No. 3",))
    return ok


if __name__ == "__main__":
    import sys
    sys.exit(0 if _selftest(verbose=True) else 1)
