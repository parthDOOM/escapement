#!/usr/bin/env python3
"""The bounded core check (esc_core.sby `bmc`), split into one SymbiYosys task per assertion
group and run side by side: split_core.py's method, for the bounded task.

    python3 split_bmc.py [--jobs N] [--depth D] [--engine "smtbmc boolector"] [--timeout S]
                         [--json FILE] [TASK ...]                                (from formal/)

Each task keeps the assertions written on one source line (or one `lemma-group`) and removes
the others; every assumption stays in every task (reset at step 0, the static configuration,
the ESC_AHEAD lemmas). A bounded check never uses an assertion as a lemma, so removing the
others cannot hide a failure of the kept ones: the union of the tasks checks exactly what the
single `bmc` task checks, to the same depth (esc_core.sby's, unless --depth). What the split
changes is the time. Measured on v1.7 (11-10): the single task on yices was still on step 19
after 16.8 h; split, 39 of 40 tasks passed depth 20 on yices in at most 3 h 17 m, and the two
slowest (P2 never late, esc_core; H1, esc_ctx) took 22 and 52 min on boolector, so boolector
is the default engine. A failure prints the assertion and the step.

The groups are read from the elaborated design, so the split follows the RTL as it changes.
TASKs run only those groups (the names it prints, e.g. `esc_ctx_462`).
"""
import argparse
import json
import re
import subprocess
import sys
import time
from pathlib import Path

from split_core import HERE, SBY, assertion_groups, sections, task_lines, task_names

OUT = HERE / "esc_core_bmcsplit.sby"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--jobs", type=int, default=1,
                    help="tasks side by side (default 1; each solver can need about 2.5 GB)")
    ap.add_argument("--depth", type=int, help="default: esc_core.sby's bmc depth")
    ap.add_argument("--engine", default="smtbmc boolector")
    ap.add_argument("--timeout", type=int, default=14400, help="seconds per task")
    ap.add_argument("--json", help="also write each task's result to this file")
    ap.add_argument("only", nargs="*", metavar="TASK", help="run only these tasks")
    a = ap.parse_args()

    sec = sections(SBY.read_text())
    tasks_declared = task_names(sec)
    script = task_lines(sec["script"], "bmc", tasks_declared)
    files = [f.strip() for f in sec["files"] if f.strip()]
    if a.depth is None:
        opts = task_lines(sec["options"], "bmc", tasks_declared)
        a.depth = int(next(o.split()[1] for o in opts if o.startswith("depth")))
    groups = assertion_groups(script, files, "esc_core_bmcsplit.list")
    src = {f: (HERE.parent / "src" / f).read_text().splitlines() for f, _ in groups}

    tasks = {}
    for f, ln in groups:
        m = re.search(r"lemma-group:\s*(\w+)", src[f][ln - 1])
        tasks.setdefault(m.group(1) if m else f"{Path(f).stem}_{ln}", []).append((f, ln))
    unknown = set(a.only) - set(tasks)
    if unknown:
        sys.exit(f"no such task: {' '.join(sorted(unknown))} (tasks: {' '.join(tasks)})")
    names = a.only or list(tasks)

    body = ["# Generated by split_bmc.py from esc_core.sby (task bmc); do not edit.", "[tasks]",
            *names, "", "[options]", "mode bmc", f"depth {a.depth}", f"timeout {a.timeout}", "",
            "[engines]", a.engine, "", "[script]"]
    for s in script:
        body.append(s)
        if s.startswith("prep"):
            for n in names:
                keep = " ".join(f"n:$assert${f}:{ln}$*" for f, ln in tasks[n])
                body.append(f"{n}: chformal -assert -remove n:$assert$* {keep}"
                            f"{' %u' * (len(tasks[n]) - 1)} %d")
    body += ["", "[files]", *files, ""]
    OUT.write_text("\n".join(body))
    n_assert = sum(len(tasks[n]) for n in names)
    print(f"{len(names)} tasks ({n_assert} assertion lines), engine {a.engine}, depth {a.depth}, "
          f"{a.jobs} at a time, {a.timeout} s each", flush=True)

    t0 = time.time()
    subprocess.run(["sby", "-f", "-j", str(a.jobs), OUT.name, *names], cwd=HERE,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    wall = time.time() - t0

    worst, record = 0, []
    for n in names:
        (f, ln), more = tasks[n][0], len(tasks[n]) - 1
        d = HERE / f"esc_core_bmcsplit_{n}"
        status = (d / "status").read_text().split()[0] if (d / "status").exists() else "ERROR"
        log = (d / "logfile.txt").read_text() if (d / "logfile.txt").exists() else ""
        m = re.search(r"Elapsed clock time \[H:MM:SS \(secs\)\]: \S+ \((\d+)\)", log)
        secs = int(m.group(1)) if m else None
        steps = [int(x) for x in re.findall(r"Checking assertions in step (\d+)", log)]
        reached = max(steps) if steps else None
        # e.g. "failed assertion esc_core.\g_ctx[2].u_ctx ._witness_.check_... at
        # esc_ctx.v:459.26-459.56 step 4" (the cell name can contain a space)
        fail = re.search(r"failed assertion (.*?) at (\S+)(?: step (\d+))?\s*$", log, re.M)
        text = src[f][ln - 1].strip() if not more else f"group {n}: {f}:{ln} and {more} more"
        print(f"{status:8s} {secs if secs is not None else '?':>6} s  step {reached}  "
              f"{f}:{ln:<4d} {text[:64]}" + (f"  FAILED {fail.group(2)}" if fail else ""))
        worst = max(worst, {"PASS": 0, "UNKNOWN": 1, "TIMEOUT": 1}.get(status, 2))
        record.append({"task": n, "where": [f"{g}:{k}" for g, k in tasks[n]], "status": status,
                       "secs": secs, "step_reached": reached,
                       "failed": fail.group(2) if fail else None, "text": text})
    print(f"wall time {wall:.0f} s")
    if a.json:
        Path(a.json).parent.mkdir(parents=True, exist_ok=True)
        Path(a.json).write_text(json.dumps({"engine": a.engine, "depth": a.depth, "jobs": a.jobs,
                                            "wall_secs": round(wall), "tasks": record}, indent=1) + "\n")
    return worst


if __name__ == "__main__":
    sys.exit(main())
