"""Write formal/esc_isa_enc.vh, the ISA checker's encodings, from isa/isa.yaml.

The checker (formal/esc_isa_check.v) states what each instruction does from
docs/11-SEMANTICS.md; only the encodings come from here, so the assembler, the ISS and the
checker share one source for them while the RTL's decoder keeps its own constants. A typo
in either side's opcode table then shows as a failed proof.

    python scripts/gen_isa_enc.py          # rewrite formal/esc_isa_enc.vh
    python scripts/gen_isa_enc.py --check  # exit 1 if the file is out of date
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "formal" / "esc_isa_enc.vh"


def render() -> str:
    isa = yaml.safe_load((ROOT / "isa" / "isa.yaml").read_text(encoding="utf-8"))
    lines = [
        f"// Generated by scripts/gen_isa_enc.py from isa/isa.yaml (ISA {isa['version']}). Do not edit.",
        "// Encodings only: what an instruction does is written in formal/esc_isa_check.v from",
        "// docs/11-SEMANTICS.md, never generated from isa.yaml.",
        "",
        "// opcodes, word[31:24]",
    ]
    for name, o in isa["opcodes"].items():
        lines.append(f"localparam [7:0] ENC_OP_{name} = 8'h{o['op']:02X};   // format {o['format']}"
                     + (", wait class" if o.get("wait_class") else ""))
    lines += ["", "// formats: each named field's [msb, lsb]; every other payload bit is reserved"]
    for fmt, fields in isa["formats"].items():
        body = ", ".join(f"{k} [{v[0]}:{v[1]}]" for k, v in fields.items()) or "no operands"
        lines.append(f"//   {fmt:4s} {body}")
    for fmt, fields in isa["formats"].items():
        mask = 0
        for msb, lsb in fields.values():
            mask |= ((1 << (msb - lsb + 1)) - 1) << lsb
        lines.append(f"localparam [23:0] ENC_FMT_{fmt}_USED = 24'h{mask:06X};")
    # per opcode: listed at all, its format's used payload bits, wait class. Written as compare
    # logic, not case tables: Yosys turns a case table of constants into a ROM, whose read port
    # can absorb a register, a hidden state that k-induction starts anywhere (as the RTL's own
    # decoder notes, esc_core.v onehot()).
    ops = list(isa["opcodes"].items())
    eq = lambda name: f"(op == ENC_OP_{name})"
    lines += ["", "// 1 if the opcode is listed in isa.yaml (an unlisted one is ILLEGAL)",
              "function enc_listed;", "  input [7:0] op;", "  enc_listed ="]
    lines += [f"    {eq(n)}" + (" |" if i < len(ops) - 1 else ";") for i, (n, _) in enumerate(ops)]
    lines += ["endfunction", "",
              "// the payload bits an opcode's format names (0 for an unlisted opcode); every other",
              "// payload bit is reserved", "function [23:0] enc_used;", "  input [7:0] op;", "  enc_used ="]
    lines += [f"    ({{24{{{eq(n)}}}}} & ENC_FMT_{o['format']}_USED)" + (" |" if i < len(ops) - 1 else ";")
              for i, (n, o) in enumerate(ops)]
    wc = [n for n, o in ops if o.get("wait_class")]
    lines += ["endfunction", "", "// 1 for a wait-class opcode (isa.yaml wait_class)", "function enc_wait_class;",
              "  input [7:0] op;", "  enc_wait_class ="]
    lines += [f"    {eq(n)}" + (" |" if i < len(wc) - 1 else ";") for i, n in enumerate(wc)]
    lines += ["endfunction"]
    lines += ["", "// fault causes and ADMIT subcodes"]
    for name, v in isa["fault_causes"].items():
        lines.append(f"localparam [3:0] ENC_CAUSE_{name} = 4'd{v};")
    for name, v in isa["admit_subcodes"].items():
        lines.append(f"localparam [3:0] ENC_ADMIT_{name} = 4'd{v};")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_bytes().decode("utf-8") == text
        print(f"{OUT.relative_to(ROOT)}: {'up to date' if ok else 'OUT OF DATE'}")
        return 0 if ok else 1
    OUT.write_bytes(text.encode("utf-8"))
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
